using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Milvonion.UnitTests.TestSupport;

/// <summary>
/// Loads and parses the C# sources of the API projects once, so the source level architecture tests can inspect
/// the code the way it is written (formatting, comments, namespaces) instead of the compiled output.
/// Skips the calling test when the sources are not next to the test binaries (e.g. a copied artifact folder).
/// </summary>
public static class SourceCode
{
    private const string _solutionFile = "Milvonion.slnx";
    private const string _sourceFolder = "src";
    private static readonly string[] _projects = ["Milvonion.Api", "Milvonion.Application", "Milvonion.Domain", "Milvonion.Infrastructure"];
    private static readonly string[] _excludedFolders = ["bin", "obj", "Migrations"];
    private static readonly Lazy<string> _solutionRoot = new(FindSolutionRoot);
    private static readonly Lazy<IReadOnlyList<SourceFile>> _files = new(LoadFiles);

    /// <summary>
    /// All hand written C# files of the src projects. Generated code and EF migrations are excluded.
    /// </summary>
    public static IReadOnlyList<SourceFile> Files
    {
        get
        {
            if (_solutionRoot.Value == null)
                Assert.Skip($"{_solutionFile} not found above {AppContext.BaseDirectory}, sources are not available.");

            return _files.Value;
        }
    }

    /// <summary>
    /// The solution root directory, or null when the sources are not next to the test binaries.
    /// </summary>
    public static string SolutionRoot => _solutionRoot.Value;

    /// <summary>
    /// Walks up from the test binary until the directory containing the solution file is found.
    /// </summary>
    private static string FindSolutionRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);

        while (directory != null)
        {
            if (File.Exists(Path.Combine(directory.FullName, _solutionFile)) && Directory.Exists(Path.Combine(directory.FullName, _sourceFolder)))
                return directory.FullName;

            directory = directory.Parent;
        }

        return null;
    }

    private static IReadOnlyList<SourceFile> LoadFiles()
    {
        var files = new List<SourceFile>();

        foreach (var project in _projects)
        {
            var projectRoot = Path.Combine(_solutionRoot.Value, _sourceFolder, project);

            foreach (var path in Directory.EnumerateFiles(projectRoot, "*.cs", SearchOption.AllDirectories))
            {
                var relativePath = Path.GetRelativePath(projectRoot, path);
                var folders = Path.GetDirectoryName(relativePath).Split(Path.DirectorySeparatorChar, StringSplitOptions.RemoveEmptyEntries);

                if (folders.Any(_excludedFolders.Contains))
                    continue;

                var text = File.ReadAllText(path);

                if (text.Contains("<auto-generated"))
                    continue;

                var tree = CSharpSyntaxTree.ParseText(text, path: path);

                files.Add(new SourceFile(project, relativePath.Replace(Path.DirectorySeparatorChar, '/'), text, tree));
            }
        }

        return files;
    }
}

/// <summary>
/// A parsed source file of one of the src projects.
/// </summary>
/// <param name="Project">Project (and root namespace) name, e.g. Milvonion.Application.</param>
/// <param name="RelativePath">Path relative to the project folder with forward slashes.</param>
/// <param name="Text">Raw file content.</param>
/// <param name="Tree">Parsed syntax tree.</param>
public record SourceFile(string Project, string RelativePath, string Text, SyntaxTree Tree)
{
    /// <summary>
    /// Root node of the file.
    /// </summary>
    public CompilationUnitSyntax Root => (CompilationUnitSyntax)Tree.GetRoot();

    /// <summary>
    /// Folder of the file relative to the project, with forward slashes. Empty for files in the project root.
    /// </summary>
    public string Folder => Path.GetDirectoryName(RelativePath)?.Replace('\\', '/') ?? string.Empty;

    /// <summary>
    /// File name without extension.
    /// </summary>
    public string Name => Path.GetFileNameWithoutExtension(RelativePath);

    /// <summary>
    /// Returns a "Project/Path.cs(line)" location for violation messages.
    /// </summary>
    /// <param name="node"></param>
    /// <returns></returns>
    public string Location(SyntaxNode node) => Location(node.GetLocation());

    /// <summary>
    /// Returns a "Project/Path.cs(line)" location for violation messages.
    /// </summary>
    /// <param name="token"></param>
    /// <returns></returns>
    public string Location(SyntaxToken token) => Location(token.GetLocation());

    /// <summary>
    /// Returns a "Project/Path.cs(line)" location for violation messages.
    /// </summary>
    /// <param name="line">Zero based line index.</param>
    /// <returns></returns>
    public string Location(int line) => $"{Project}/{RelativePath}({line + 1})";

    private string Location(Location location) => Location(location.GetLineSpan().StartLinePosition.Line);
}
